using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using DriverCodeBaseEx.Enumerators;

namespace DriverCodeBaseEx
{
    /// <summary>   Arguments for executed job. </summary>
    public class ExecutedJobArgs : EventArgs
    {
        ////////////////////////////////////////////////////////////////////////////////////////////////////
        /// <summary>   Gets or sets the job. </summary>
        ///
        /// <value> The job. </value>
        ////////////////////////////////////////////////////////////////////////////////////////////////////
        public CommJob Job { get; set; }
        ////////////////////////////////////////////////////////////////////////////////////////////////////
        /// <summary>   Gets or sets the error code. </summary>
        ///
        /// <value> The error code. </value>
        ////////////////////////////////////////////////////////////////////////////////////////////////////
        public DriverErrorCodes ErrorCode { get; set; }
        ////////////////////////////////////////////////////////////////////////////////////////////////////
        /// <summary>   States if the errors code has to be processed. </summary>
        ///
        /// <value> True or False. </value>
        ////////////////////////////////////////////////////////////////////////////////////////////////////
        bool genErr = false;
        public bool GeneralError { 
            get { return genErr; }
            set { genErr = value; } 
        }
        ////////////////////////////////////////////////////////////////////////////////////////////////////
        /// <summary>   Gets or sets the receive bytes. </summary>
        ///
        /// <value> The receive bytes. </value>
        ////////////////////////////////////////////////////////////////////////////////////////////////////
        public long RxBytes { get; set; }
        ////////////////////////////////////////////////////////////////////////////////////////////////////
        /// <summary>   Gets or sets the transmit bytes. </summary>
        ///
        /// <value> The transmit bytes. </value>
        ////////////////////////////////////////////////////////////////////////////////////////////////////
        public long TxBytes { get; set; }
        ////////////////////////////////////////////////////////////////////////////////////////////////////
        /// <summary>   Gets or sets the values. </summary>
        ///
        /// <value> The values. </value>
        ////////////////////////////////////////////////////////////////////////////////////////////////////
        public object Values { get; set; }

        /// <summary>   The changedtags. </summary>
        List<Tag> changedtags;
        ////////////////////////////////////////////////////////////////////////////////////////////////////
        /// <summary>   Gets the changed tags. </summary>
        ///
        /// <value> The changed tags. </value>
        ////////////////////////////////////////////////////////////////////////////////////////////////////
        public List<Tag> ChangedTags 
        {
            get 
            {
                if (changedtags == null)
                    changedtags = new List<Tag>();

                return changedtags;
            }
        }

        ////////////////////////////////////////////////////////////////////////////////////////////////////
        /// <summary>   Gets or sets the Timestamp. </summary>
        ///
        /// <value> The Timestamp. </value>
        ////////////////////////////////////////////////////////////////////////////////////////////////////
        DateTime _Timestamp = default(DateTime);
        public DateTime Timestamp
        {
            get { return _Timestamp; }
            set { _Timestamp = value; }
        }

        ////////////////////////////////////////////////////////////////////////////////////////////////////
        /// <summary>   Gets or sets the Last job's execution time. </summary>
        ///
        /// <value> The Timestamp. </value>
        ////////////////////////////////////////////////////////////////////////////////////////////////////
        DateTime _LastExecutionTime = DateTime.UtcNow;
        public DateTime LastExecutionTime
        {
            get { return _LastExecutionTime; }
            set { _LastExecutionTime = value; }
        }
    }
}
