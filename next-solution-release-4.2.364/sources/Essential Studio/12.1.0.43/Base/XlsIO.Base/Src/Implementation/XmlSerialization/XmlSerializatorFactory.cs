using System;
using System.Collections;
using System.Reflection;

using Syncfusion.XlsIO.Interfaces.XmlSerialization;
using System.Collections.Generic;

namespace Syncfusion.XlsIO.Implementation.XmlSerialization
{
    ///<exclude/>
	/// <summary>
	/// Summary description for XmlSerializatorFactory.
	/// </summary>
	public sealed class XmlSerializatorFactory
	{
    #region Class members
    /// <summary>
    /// Dictionary with serializators. Key - int value of ExcelXmlSaveType,
    /// value - instance of a serializator.
    /// </summary>
    private static Dictionary<int, IXmlSerializator> s_dicSerializators = new Dictionary<int, IXmlSerializator>();
    #endregion

    #region Class Initialize/Finalize methods
    /// <summary>
    /// Initializes static members of the XmlSerializatorFactory class. Fills internal dictionary with serializators.
    /// </summary>
    static XmlSerializatorFactory()
    {
      RegisterXmlSerializator( ExcelXmlSaveType.DLS, typeof( DLSXmlSerializator ) );
      RegisterXmlSerializator( ExcelXmlSaveType.MSExcel, typeof( WorkbookXmlSerializator ) );
    }
    /// <summary>
    /// Prevents a default instance of the XmlSerializatorFactory class from being created.	
    /// </summary>
    private XmlSerializatorFactory()
    {
    }
    #endregion

    #region Class methods
    /// <summary>
    /// Registers xml serializator.
    /// </summary>
    /// <param name="saveType">Xml file format generated by serializator.</param>
    /// <param name="type">Type that serializes into xml.</param>
    public static void RegisterXmlSerializator( ExcelXmlSaveType saveType, Type type )
    {
      if( type == null )
        throw new ArgumentNullException( "type" );

      IXmlSerializator serializator = ( IXmlSerializator )Activator.CreateInstance( type );
      s_dicSerializators.Add( ( int )saveType, serializator );
    }
    /// <summary>
    /// Returns serializator corresponding to the specified save type.
    /// </summary>
    /// <param name="saveType">Save type to get serializator for.</param>
    /// <returns>Serializator corresponding to the specified save type.</returns>
    public static IXmlSerializator GetSerializator( ExcelXmlSaveType saveType )
    {
      return s_dicSerializators[ ( int )saveType ];
    }
    #endregion
  }
}
