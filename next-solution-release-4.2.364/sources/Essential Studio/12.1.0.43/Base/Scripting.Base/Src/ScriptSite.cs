using System;
using System.Collections;
using System.Diagnostics;

using Microsoft.Vsa;

namespace Syncfusion.Scripting
{
  /// <summary>
  /// Provides the script engine with access to objects referenced by the
  /// script.
  /// </summary>
  /// <remarks>
  /// <para>
  /// A ScriptSite contains objects that are used as global variables and event
  /// sources by the script. The objects must be registered by the hosting
  /// application before the script is compiled and executed by the script
  /// engine. Objects are registered using the
  /// <see cref="Syncfusion.Scripting.ScriptSite.RegisterEventSource"/>
  /// and
  /// <see cref="Syncfusion.Scripting.ScriptSite.RegisterGlobalInstance"/>
  /// methods. The script engine accesses the objects using the
  /// <see cref="Syncfusion.Scripting.ScriptSite.GetGlobalInstance"/>
  /// and
  /// <see cref="Syncfusion.Scripting.ScriptSite.GetEventSourceInstance"/>
  /// methods.
  /// </para>
  /// <para>
  /// The ScriptSite also contains the compiled state of the script. The
  /// compiled state is the compiled byte-code and debug information used by
  /// the script engine during execution. The compiled state can be put into
  /// the ScriptSite by calling the
  /// <see cref="Syncfusion.Scripting.ScriptSite.SetCompiledState"/> method and
  /// passing it the script engine after the script has been compiled. The
  /// compiled state can be accessed by calling the
  /// <see cref="Syncfusion.Scripting.ScriptSite.GetCompiledState"/> method. 
  /// </para>
  /// </remarks>
  public class ScriptSite : IVsaSite
  {
    #region Constructors
    /// <summary>
    /// Default constructor.
    /// </summary>
    public ScriptSite()
    {
    }
    #endregion

    #region Public Methods
    /// <summary>
    /// Removes all event sources, global instances, and compiled code from the site.
    /// </summary>
    public virtual void Clear()
    {
      this.scriptPE = null;
      this.scriptPDB = null;
    }

    /// <summary>
    /// Registers and event source with the site.
    /// </summary>
    /// <param name="name">Name of the event source</param>
    /// <param name="obj">Event source object</param>
    public virtual void RegisterEventSource( string name, object obj )
    {
      throw new InvalidOperationException();
    }

    /// <summary>
    /// Registers a global instance with the site.
    /// </summary>
    /// <param name="name">Name of the global instance</param>
    /// <param name="obj">Global instance object</param>
    public virtual void RegisterGlobalInstance( string name, object obj )
    {
      throw new InvalidOperationException();
    }

    /// <summary>
    /// Clears out the compiled state of the script.
    /// </summary>
    public void ClearCompiledState()
    {
      this.scriptPE = null;
      this.scriptPDB = null;
    }

    /// <summary>
    /// Attaches the compiled state of the given script engine to the site.
    /// </summary>
    /// <param name="scriptEngine">Script engine that contains compiled state</param>
    public void SetCompiledState( IVsaEngine scriptEngine )
    {
      if( scriptEngine == null )
      {
        throw new ArgumentNullException();
      }

      this.scriptPE = null;
      this.scriptPDB = null;
      scriptEngine.SaveCompiledState( out this.scriptPE, out this.scriptPDB );
    }
    #endregion

    #region Public Events
    /// <summary>
    /// Fired when an error occurs during compilation.
    /// </summary>
    public event VsaErrorEventHandler CompileError;
    #endregion

    #region IVsaSite Interface
    /// <summary>
    /// Gets a reference to an event source previously added to a script engine using
    /// the IVsaCodeItem.AddEventSource method.
    /// </summary>
    /// <param name="itemName"></param>
    /// <param name="eventSourceName"></param>
    /// <returns></returns>
    public virtual object GetEventSourceInstance( string itemName, string eventSourceName )
    {
      return null;
    }

    /// <summary>
    /// Gets a reference to a global item, such as the host-provided application object.
    /// </summary>
    /// <param name="globInstanceName"></param>
    /// <returns></returns>
    public virtual object GetGlobalInstance( string globInstanceName )
    {
      return null;
    }

    /// <summary>
    /// Notifies the host about events generated by the .NET script engine.
    /// </summary>
    /// <param name="notify"></param>
    /// <param name="info"></param>
    public virtual void Notify( string notify, object info )
    {
      Debug.WriteLine( notify );
      // TODO:  This should fire an event
    }

    /// <summary>
    /// Notifies the host about how to respond to compiler errors encountered
    /// by the script engine.
    /// </summary>
    /// <param name="error"></param>
    /// <returns></returns>
    public virtual bool OnCompilerError( IVsaError error )
    {
      this.OnCompileError( new VsaErrorEventArgs( error ) );
      return true;
    }

    /// <summary>
    /// Gets the compiled state of a script engine, and, optionally,
    /// associated debugging information.
    /// </summary>
    /// <param name="pe"></param>
    /// <param name="debugInfo"></param>
    public virtual void GetCompiledState( out byte[] pe, out byte[] debugInfo )
    {
      pe = this.scriptPE;
      debugInfo = this.scriptPDB;
    }
    #endregion

    #region Implementation Methods
    /// <summary>
    /// Called when an error occurs during compilation.
    /// </summary>
    /// <param name="evtArgs"></param>
    protected virtual void OnCompileError( VsaErrorEventArgs evtArgs )
    {
      if( this.CompileError != null )
      {
        this.CompileError( this, evtArgs );
      }
    }
    #endregion

    #region Fields
    private byte[] scriptPE = null;
    private byte[] scriptPDB = null;
    #endregion
  }

  /// <summary>
  /// 
  /// </summary>
  public class DefaultScriptSite : ScriptSite
  {
    #region Constructors
    /// <summary>
    /// Default constructor.
    /// </summary>
    public DefaultScriptSite()
    {
    }
    #endregion

    #region Public Methods
    /// <summary>
    /// Removes all event sources, global instances, and compiled code from the site.
    /// </summary>
    public override void Clear()
    {
      base.Clear();
      this.eventSourceTable.Clear();
      this.globalInstanceTable.Clear();
    }

    /// <summary>
    /// Registers and event source with the site.
    /// </summary>
    /// <param name="name">Name of the event source</param>
    /// <param name="obj">Event source object</param>
    public override void RegisterEventSource( string name, object obj )
    {
      if( !this.eventSourceTable.Contains( name ) )
      {
        this.eventSourceTable.Add( name, obj );
      }
    }

    /// <summary>
    /// Registers a global instance with the site.
    /// </summary>
    /// <param name="name">Name of the global instance</param>
    /// <param name="obj">Global instance object</param>
    public override void RegisterGlobalInstance( string name, object obj )
    {
      if( !this.globalInstanceTable.Contains( name ) )
      {
        this.globalInstanceTable.Add( name, obj );
      }
    }

    /// <summary>
    /// Gets a reference to an event source previously added to a script engine using
    /// the IVsaCodeItem.AddEventSource method.
    /// </summary>
    /// <param name="itemName"></param>
    /// <param name="eventSourceName"></param>
    /// <returns></returns>
    public override object GetEventSourceInstance( string itemName, string eventSourceName )
    {
      object evtSrcObj = null;

      if( this.eventSourceTable.Contains( eventSourceName ) )
      {
        evtSrcObj = this.eventSourceTable[ eventSourceName ];
      }

      return evtSrcObj;
    }

    /// <summary>
    /// Gets a reference to a global item, such as the host-provided application object.
    /// </summary>
    /// <param name="globInstanceName"></param>
    /// <returns></returns>
    public override object GetGlobalInstance( string globInstanceName )
    {
      object globObj = null;

      if( this.globalInstanceTable.Contains( globInstanceName ) )
      {
        globObj = globalInstanceTable[ globInstanceName ];
      }

      return globObj;
    }
    #endregion

    #region Fields
    private Hashtable eventSourceTable = new Hashtable();
    private Hashtable globalInstanceTable = new Hashtable();
    #endregion
  }
}