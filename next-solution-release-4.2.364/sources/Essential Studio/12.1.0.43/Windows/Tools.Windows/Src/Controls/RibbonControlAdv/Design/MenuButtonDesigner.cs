using System;
using System.Windows.Forms;
using System.Windows.Forms.Design;
using System.Windows.Forms.Design.Behavior;
using System.Drawing;
using System.Drawing.Design;
using System.ComponentModel;
using System.ComponentModel.Design;

namespace Syncfusion.Windows.Forms.Tools.Design
{
	#region MenuButtonGlyph
	class MenuButtonGlyph : Glyph
	{
		#region MenuButtonBehavior
		class MenuButtonBehavior : Behavior
		{
			#region Constructors
			public MenuButtonBehavior()
				: base()
			{
			}
			#endregion

			#region Overrides
			public override bool OnMouseDown(Glyph g, MouseButtons button, Point mouseLoc)
			{
				bool bResult = false;

				MenuButtonGlyph mbGlyph = g as MenuButtonGlyph;

				if (mbGlyph != null)
				{
					Rectangle bounds = mbGlyph.Bounds;

					if (bounds.Contains(mouseLoc))
					{
						ToolStripDropDownItem item = mbGlyph.Item;

						if (item != null )
						{
							ToolStripDropDown dropDown = item.DropDown;
							if (!dropDown.Visible)
							{
								if (dropDown.IsAutoGenerated)
								{
									item.ShowDropDown();
								}
								else
								{
									mbGlyph.m_selectionSvc.SetSelectedComponents(new IComponent[] { dropDown }, SelectionTypes.Replace);
								}
							}
							else
							{
								if (dropDown.IsAutoGenerated)
								{
									mbGlyph.m_selectionSvc.SetSelectedComponents(new IComponent[] { dropDown });
								}
							}
						}
						bResult = true;
					}
				}

				return bResult;
			}
			#endregion
		}
		#endregion

		#region Constructors
		public MenuButtonGlyph(RibbonControlAdv control)
			: base(new MenuButtonBehavior())
		{
			m_control = control;

			m_behaviorSvc = DesignerUtils.GetBehaviorService(control);
			m_selectionSvc = DesignerUtils.GetSelectionService(control);
		}
		#endregion

		#region Properties
		/// <summary>
		/// 
		/// </summary>
		public override Rectangle Bounds
		{
			get
			{
				Rectangle rc = Rectangle.Empty;
				if (m_behaviorSvc != null)
				{
					if (m_control != null && m_control.Visible)
					{
						RibbonControlAdvHeader header = m_control.HeaderInternal;
						if (header != null)
						{
							ToolStripItem button = header.MenuButton;
							if (button.Visible)
							{
								rc = button.Bounds;
								rc.Location = m_behaviorSvc.MapAdornerWindowPoint(header.Handle, rc.Location);
							}
						}
					}
				}
				return rc;
			}
		}
		/// <summary>
		/// 
		/// </summary>
		ToolStripDropDownItem Item
		{
			get { return m_control.HeaderInternal.MenuButton; }
		}
		#endregion

		#region Overrides
		/// <summary>
		/// 
		/// </summary>
		/// <param name="p"></param>
		/// <returns></returns>
		public override Cursor GetHitTest(Point p)
		{
			if (m_control != null && m_control.Visible)
			{
				if (this.Bounds.Contains(p))
				{
					return Cursors.Hand;
				}
			}
			return null;
		}
		/// <summary>
		/// 
		/// </summary>
		/// <param name="pe"></param>
		public override void Paint(PaintEventArgs pe)
		{
		}
		#endregion

		#region Fields
		RibbonControlAdv m_control;
		BehaviorService m_behaviorSvc = null;
		ISelectionService m_selectionSvc = null;
		#endregion
	}
	#endregion
}
#endif
