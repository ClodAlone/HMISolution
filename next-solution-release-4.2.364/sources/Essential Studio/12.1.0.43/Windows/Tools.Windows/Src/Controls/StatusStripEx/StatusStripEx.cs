        /// <summary>
        /// Layout engine for StatusStripEx.
        /// </summary>
        private class StatusStripExLayoutEngine : LayoutEngine
        {
            #region Overrides
            /// <summary>
            /// Lays out toolstrip items in StatusStripEx.
            /// </summary>
            /// <param name="container">Container object</param>
            /// <param name="layoutEventArgs">LayoutEventArgs that contains the event data.</param>
            /// <returns>returns bool value</returns>
            public override bool Layout(object container, LayoutEventArgs layoutEventArgs)
            {
                StatusStripEx parent = (StatusStripEx)container;

                int iParentHeight = parent.Height;

                Rectangle rcDisplay = parent.DisplayRectangle;

                Size szDisplaySize = rcDisplay.Size;
                int iPosition = rcDisplay.Right;

                int iTop = 0;
                int iParentPaddingTop = parent.Padding.Top;
                int iParentPaddingLeft = parent.Padding.Left;

                bool bEnoughForStatusControlsItems = false;

                // Locate StatusControlsItems items.
                for (int i = parent.StatusControlsItems.Count - 1; i >= 0; i--)
                {
                    ToolStripItem item = parent.StatusControlsItems[i];

                    if (item != null && item.Owner != null)
                    {
                        iTop = item.Margin.Top + iParentPaddingTop;

                        if (item.AutoSize)
                        {
                            item.Size = item.GetPreferredSize(szDisplaySize);
                            iTop = (iParentHeight - item.Height) / 2;
                        }

                        int len = iParentPaddingLeft + item.Width;

                        if (item.Available)
                        {
                            if (iPosition <= len || bEnoughForStatusControlsItems)
                            {
                                SetItemLocationRTL(parent, item, new Point(-item.Width - 1, iTop));
                                bEnoughForStatusControlsItems = true;
                            }
                            else
                            {
                                SetItemLocationRTL(parent, item, new Point(iPosition - item.Width, iTop));
                                iPosition -= item.Width + MARGIN;
                            }
                        }
                    }
                }

                int iLeftPosition = rcDisplay.Left;
                bool bEnoughForNotificationsItems = false;

                // Locate NotificationsItems that represent IStatusItem interface.
                for (int i = 0, count = parent.NotificationsItems.Count; i < count; i++)
                {
                    ToolStripItem item = parent.NotificationsItems[i];

                    if (item != null && item.Owner != null)
                    {
                        iTop = item.Margin.Top + iParentPaddingTop;

                        if (item.AutoSize)
                        {
                            item.Size = item.GetPreferredSize(szDisplaySize);
                            iTop = (iParentHeight - item.Height) / 2;
                        }

                        bool bIsEndOfGroup = false;

                        IStatusItem statusItem = item as IStatusItem;

                        if (statusItem != null)
                        {
                            bIsEndOfGroup = statusItem.EndOfGroup;
                        }

                        if (item.Available)
                        {
                            if ((iLeftPosition + item.Width < iPosition - MAIN_SEPARATOR_WIDTH)
                                && !bEnoughForNotificationsItems
                                && !bEnoughForStatusControlsItems)
                            {
                                SetItemLocationRTL(parent, item, new Point(iLeftPosition, iTop));
                                iLeftPosition += item.Width + SEPARATOR_WIDTH;
                            }
                            else
                            {
                                SetItemLocationRTL(parent, item, new Point(-item.Width - 1, iTop));
                                bEnoughForNotificationsItems = true;
                            }
                        }

                        // Add separator.
                        if (bIsEndOfGroup && !bEnoughForNotificationsItems && parent.Separators != null)
                        {
                            AddSeparatorsPositionRTL(parent, iLeftPosition - SEPARATOR_WIDTH);
                        }
                    }
                }

                // Add main separator.
                SetSeparatorPositionRTL(parent, iPosition - MAIN_SEPARATOR_WIDTH);

                return parent.AutoSize;
            }
            #endregion

            #region Implementation
            /// <summary> Set item location depending on RTL property. </summary>
            /// <param name="parent">Status Strip</param>
            /// <param name="item">Toolstrip Item</param>
            /// <param name="location">Location point</param>
            private void SetItemLocationRTL(StatusStripEx parent, ToolStripItem item, Point location)
            {
                if (parent.RightToLeft == RightToLeft.No)
                {
                    parent.SetItemLocation(item, location);
                }
                else
                {
                    if (location.X > 0)
                    {
                        Point newLocation = new Point(parent.Width - location.X - item.Width + parent.DisplayRectangle.X, location.Y);

                        parent.SetItemLocation(item, newLocation);
                    }
                    else
                    {
                        parent.SetItemLocation(item, location);
                    }
                }
            }

            /// <summary> Set main separator location depending on RTL property. </summary>
            /// <param name="parent">Sgtatus Strip</param>
            /// <param name="position">Separator position</param>
            private void SetSeparatorPositionRTL(StatusStripEx parent, int position)
            {
                if (parent.RightToLeft == RightToLeft.No)
                {
                    parent.SeparatorPosition = (position > 0) ? position : 0;
                }
                else
                {
                    parent.SeparatorPosition = (position > 0) ? parent.Width - position - MAIN_SEPARATOR_WIDTH + parent.DisplayRectangle.X : 0;
                }
            }

            /// <summary> Set separator position and add it to list depending on RTL property. </summary>
            /// <param name="parent">Status StripEx</param>
            /// <param name="position">Separator position</param>
            private void AddSeparatorsPositionRTL(StatusStripEx parent, int position)
            {
                if (parent.RightToLeft == RightToLeft.No)
                {
                    parent.Separators.Add(position);
                }
                else
                {
                    parent.Separators.Add(parent.Width - position - SEPARATOR_WIDTH + parent.DisplayRectangle.X);
                }
            }
            #endregion
        }
