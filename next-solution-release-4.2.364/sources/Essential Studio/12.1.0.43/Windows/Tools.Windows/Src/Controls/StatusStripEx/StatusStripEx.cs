       public class GripWindow : NativeWindow
        {
            #region Constructor
         
            public GripWindow(Control control)
            {
                m_control = control;
                AssignHandle(m_control.Handle);
            }
            #endregion

            #region Overrides
            protected override void WndProc(ref Message m)
            {
                switch ((Msg)m.Msg)
                {
                    case Msg.WM_PAINT:
                        StatusStripEx statusStrip = m_control.Parent as StatusStripEx;
                        if (statusStrip != null)
                        {
                            PAINTSTRUCT paintSt = new PAINTSTRUCT();
                            IntPtr hdc = WindowsAPI.BeginPaint(m.HWnd, ref paintSt);

                            using (Graphics g = Graphics.FromHdc(hdc))
                            {
                                Point pt = m_control.Location;
                                g.TranslateTransform(-(pt.X + 1), -pt.Y);

                                ToolStripRenderEventArgs ea = new ToolStripRenderEventArgs(g, statusStrip);
                                ToolStripRenderer renderer = statusStrip.Renderer;

                                renderer.DrawToolStripBackground(ea);
                                renderer.DrawStatusStripSizingGrip(ea);
                            }
                            WindowsAPI.EndPaint(m.HWnd, ref paintSt);

                            m.Result = IntPtr.Zero;
                            return;
                        }
                        break;
                }
                base.WndProc(ref m);
            }
            #endregion

            #region Fields
           private Control m_control;
            #endregion
        }
        #endregion

        #endregion

        #region Overrides
        protected override void OnHandleDestroyed(EventArgs e)
        {
            if (m_notificationsItems != null)
            {
                m_notificationsItems.Clear();
                m_notificationsItems = null;
            }
            if (m_statusControlsItems != null)
            {
                m_statusControlsItems.Clear();
                m_statusControlsItems = null;
            }
            base.OnHandleDestroyed(e);
        }

        protected override void Dispose(bool disposing)
        {
            m_bDisposing = true;

            if (disposing)
            {
                if (this.m_menuStrip != null)
                {
                    this.m_menuStrip.StatusStrip = null;
                    this.m_menuStrip.Dispose();
                    this.m_menuStrip = null;
                }

                if (m_separators != null)
                {
                    m_separators.Clear();
                    m_separators = null;
                }

                this.ContextMenuStrip = null;
                
                this.Renderer = null;
                
                office12_color_table_mgdColors = null;
                
                m_layoutEngine = null;
            }

            base.Dispose(disposing);
            base.DestroyHandle();

            m_bDisposing = false;
        }

        /// <summary>
        /// Retrieves the size of a rectangular area into which a control can be fitted. 
        /// </summary>
        /// <param name="proposedSize">Proposed size</param>
        /// <returns> Returns Size</returns>
        [Description("Retrieves the size of a rectangular area into which a control can be fitted.")]
        public override Size GetPreferredSize(Size proposedSize)
        {
            Size szDefault = this.DefaultSize - this.Padding.Size;

            int width = MAIN_SEPARATOR_WIDTH;
            int height = szDefault.Height;

            ToolStripItemCollection controlsItems = this.StatusControlsItems;

            int controlsCount = controlsItems.Count;
            if (controlsCount > 0)
            {
                for (int i = 0, count = controlsCount; i < count; i++)
                {
                    ToolStripItem item = controlsItems[i];
                    if (item != null && item.Available)
                    {
                        Size szItem = item.AutoSize ? item.GetPreferredSize(Size.Empty) : item.Size;

                        width += szItem.Width + MARGIN;
                        height = Math.Max(height, szItem.Height + item.Margin.Vertical);
                    }
                }
            }

            ToolStripItemCollection notificationsItems = this.NotificationsItems;

            int notificationsCount = notificationsItems.Count;
            if (notificationsCount > 0)
            {
                for (int i = 0, count = notificationsCount; i < count; i++)
                {
                    ToolStripItem item = notificationsItems[i];
                    if (item != null && item.Available)
                    {
                        Size szItem = item.AutoSize ? item.GetPreferredSize(Size.Empty) : item.Size;

                        width += szItem.Width + SEPARATOR_WIDTH;
                        height = Math.Max(height, szItem.Height + item.Margin.Vertical);
                    }
                }
            }
            else
            {
                if (width < szDefault.Width)
                {
                    width = szDefault.Width;
                }
            }

            return new Size(width + this.Padding.Horizontal, height + this.Padding.Vertical);
        }
 
