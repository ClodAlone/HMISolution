        #region Message handlers
   
        private bool OnNcHitTest(ref Message m)
        {
            Form form = this.Parent as Form;
            if (form != null && form.TopLevel)
            {
                WindowStyles style = (WindowStyles)WindowsAPI.GetWindowLong(form.Handle, (int)SetWindowLongOffsets.GWL_STYLE);
                if ((style & (WindowStyles.WS_MAXIMIZE | WindowStyles.WS_MINIMIZE)) == 0)
                {
                    POINT pt = new POINT(WindowsAPI.GET_X_LPARAM((int)m.LParam), WindowsAPI.GET_Y_LPARAM((int)m.LParam));
                    WindowsAPI.MapWindowPoints(IntPtr.Zero, this.Handle, ref pt, 1);

                    if (this.SizingGrip && this.SizeGripBounds.Contains(pt.x, pt.y))
                    {
                        m.Result = (IntPtr)HitTest.HTBOTTOMRIGHT;
                        return true;
                    }
                }
            }
            return false;
        }
