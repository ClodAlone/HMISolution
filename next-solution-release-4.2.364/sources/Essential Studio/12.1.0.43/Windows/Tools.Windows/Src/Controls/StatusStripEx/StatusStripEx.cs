        protected override void OnParentChanged(EventArgs e)
        {
            base.OnParentChanged(e);
            if (!m_bDisposing)
            {
                if (Inizilise)
                    Inizilise = false;
                if (this.VisualStyle == StatusStripExStyle.Default)
                {
                    UpdateRenderer();
                }
                else
                {
                    UpdateMetroRenderer();
                }
            }
            else
                UpdateRenderer(true);
        }

        protected override void OnRendererChanged(EventArgs e)
        {
            if (!m_bDisposing)
            {
                if (!(this.Renderer is MetroStatusStripExRenderer))
                {
                    if (this.VisualStyle == StatusStripExStyle.Default)
                    {
                        if (!(this.Renderer is StatusStripExRenderer))
                            UpdateRenderer();
                    }
                    else
                    {
                        UpdateMetroRenderer();
                    }
                }
            }

            else
                UpdateRenderer(true);

            base.OnRendererChanged(e);
        }
   
