        /// <summary> Update renderer according to choiced color scheme. </summary>
        internal void UpdateRenderer()
        {
            switch (this.OfficeColorScheme)
            {
                case ToolStripEx.ColorScheme.Managed:
                    this.Renderer = new StatusStripExRenderer(office12_color_table_mgdColors);
                    break;
                case ToolStripEx.ColorScheme.Silver:
                    this.Renderer = new StatusStripExRenderer(new Office12ColorTable());
                    break;
                case ToolStripEx.ColorScheme.Blue:
                    OfficeBlue office_Blue = new OfficeBlue();
                    this.Renderer = new StatusStripExRenderer(office_Blue);
                    break;
                case ToolStripEx.ColorScheme.Black:
                    this.Renderer = new StatusStripExRenderer(new OfficeBlack());
                    break;
            }
        }
        internal void UpdateMetroRenderer()
        {
            this.Renderer = new MetroStatusStripExRenderer(MetroColor, this.BackColor);
        }
        internal void UpdateRenderer(bool disposing)
        {
            if (disposing)
            {
                this.Renderer = null;
            }
        }
        

        /// <summary> Gets ColorScheme according to type. </summary>
        /// <param name="type">Colorscheme type</param>
        /// <returns>Returns Color Scheme</returns>
        private ToolStripEx.ColorScheme GetOfficeColorScheme(RibbonForm.ColorSchemeType type)
        {
            ToolStripEx.ColorScheme color;

            switch (type)
            {
                case RibbonForm.ColorSchemeType.Silver:
                    color = ToolStripEx.ColorScheme.Silver;
                    break;
                case RibbonForm.ColorSchemeType.Black:
                    color = ToolStripEx.ColorScheme.Black;
                    break;
                case RibbonForm.ColorSchemeType.Blue:
                    color = ToolStripEx.ColorScheme.Blue;
                    break;
                default:
                    color = ToolStripEx.ColorScheme.Managed;
                    break;
            }

            return color;
        }
