        private Binding _valueBinding;
        public Binding ValueBinding
        {
            get
            {
                if (_valueBinding == null && !String.IsNullOrEmpty(MappingName))
                {
                    _valueBinding = MappingName.CreateEditableBinding();
                    if (_columnWrapper != null)
                        _columnWrapper.SetValueBinding(_valueBinding);
                    isvaluebindingcreated = true;
                }
                else if (_valueBinding == null && _displayBinding != null)
                {

#if WinRT
                    _valueBinding = _displayBinding.CreateEditBinding(false);
#else
                    _valueBinding = _displayBinding.CreateEditBinding(this.UpdateTrigger, false);
#endif
                    if (_columnWrapper != null)
                        _columnWrapper.SetValueBinding(_valueBinding);
                    isvaluebindingcreated = true;
                }
                return _valueBinding;
            }
            set
            {
                SetValueBinding(false, value);
            }
        }

        private void SetValueBinding(bool internalset, Binding value)
      {
          _valueBinding = value;
          if (_columnWrapper != null)
              _columnWrapper.SetValueBinding(_valueBinding);
         if (!internalset)
              isvaluebindingcreated = false;
          UpdateBindingInfo();
      }

        private Binding _displayBinding;
        public Binding DisplayBinding
        {
            get
            {
                if (_displayBinding == null && ValueBinding != null)
                {
                    _displayBinding = ValueBinding.CreateDisplayBinding();
                    if (_columnWrapper != null)
                        _columnWrapper.SetDisplayBinding(_displayBinding);
                    isdisplayingbindingcreated = true;
                }
#if !WP
#if !WinRT

                if ((this is GridCurrencyColumn || this is GridPercentColumn || this is GridDateTimeColumn || this is GridTimeSpanColumn|| this is GridNumericColumn || this is GridMaskColumn) && _displayBinding.Converter == null)
                {
                    _displayBinding.Converter=new CultureFormatConverter(this);
                }
#else
                if ((this is GridNumericColumn || this is GridDateTimeColumn) && _displayBinding.Converter == null)
                {
                    _displayBinding.Converter=new CultureFormatConverter(this);
                }
#endif
#endif
                if ((this is GridComboBoxColumn && _displayBinding.Converter == null))
                {
                    _displayBinding.Converter = new DisplayMemberConverter(this);
                }

                if ((this is GridMultiColumnDropDownList && _displayBinding.Converter == null))
                {
                    _displayBinding.Converter = new DisplayMemberConverter(this);
                }

                return _displayBinding;
            }
            set
            {
                SetDisplayBinding(false, value);
            }
        }

        private void SetDisplayBinding(bool internalset, Binding value)
      {
           _displayBinding = value;
           if (_columnWrapper != null)
               _columnWrapper.SetDisplayBinding(_displayBinding);
          if (!internalset)
              isdisplayingbindingcreated = false;
           UpdateBindingInfo();
      }
