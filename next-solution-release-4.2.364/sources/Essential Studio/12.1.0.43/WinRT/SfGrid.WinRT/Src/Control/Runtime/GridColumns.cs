        public void UpdateBindingForValidation(GridValidationMode gridValidationMode)
        {

            if (this.ValueBinding != null)
            {
                Binding bind;
                if (gridValidationMode == GridValidationMode.None)
#if WinRT
                    bind = this.ValueBinding.CreateEditBinding(false);
#else
                    bind = this.ValueBinding.CreateEditBinding(this.UpdateTrigger, false);
#endif
                else
#if WinRT
                    bind = this.ValueBinding.CreateEditBinding();
#else
                    bind = this.ValueBinding.CreateEditBinding(this.UpdateTrigger);
#endif
                this.SetValueBinding(true, bind);
            }

            if (this.DisplayBinding != null)
            {
                Binding bind;
                if (gridValidationMode == GridValidationMode.None)
                    bind = this.DisplayBinding.CreateDisplayBinding(false);
                else
                    bind = this.DisplayBinding.CreateDisplayBinding();

                this.SetDisplayBinding(true, bind);
            }

