    public void SettingSelectedItemAddsToSelectedItemsCollection_MultipleMode()
    {
      _grid.SelectionMode = SelectionMode.Multiple;
      // Set the selected item, this updates the selected items collection. see SettingSelectedItemUpdatesSelectedItemsCollection_MultipleMode
      _grid.SelectedItem = _staticData[8];

      // Change the SelectedItem property. This adds the item to the selected items collection. The previous items remains selected because of multiple mode.
      _grid.SelectedItem = _staticData[3];
      Assert.AreEqual(_staticData[3], _grid.SelectedItem);
      Assert.AreEqual(2, _grid.SelectedItems.Count);
      Assert.Contains(_staticData[3], _grid.SelectedItems);

      // And so on
      _grid.SelectedItem = _staticData[5];
      Assert.AreEqual(_staticData[5], _grid.SelectedItem);
      Assert.AreEqual(3, _grid.SelectedItems.Count);
      Assert.Contains(_staticData[5], _grid.SelectedItems);
    }

    [Test]
    [STAThread]
    public void SettingSelectedItemPropertyDoesNotUpdateSelectedItemsCollectionIfItemIsAlreadySelected_MultipleMode()
    {
      _grid.SelectionMode = SelectionMode.Multiple;
      // Add some items to the selected items collection:
      _grid.SelectedItems.Add(_staticData[1]);
      _grid.SelectedItems.Add(_staticData[3]);
      _grid.SelectedItems.Add(_staticData[9]);
      _grid.SelectedItems.Add(_staticData[5]);
      // there are 4 selected items:
      Assert.AreEqual(4, _grid.SelectedItems.Count);
      // The SelectedItem property is the first item that was added:
      Assert.AreEqual(_staticData[1], _grid.SelectedItem);
      // Change the SelectedItem property to be one of the already selected items:
      _grid.SelectedItem = _staticData[9];

      // there are still 4 selected items. This is mainly to test that a duplicate item was not added to the collection as a cause of setting the SelectedItem property.
      Assert.AreEqual(4, _grid.SelectedItems.Count);
      Assert.Contains(_staticData[1], _grid.SelectedItems);
      Assert.Contains(_staticData[3], _grid.SelectedItems);
      Assert.Contains(_staticData[9], _grid.SelectedItems);
      Assert.Contains(_staticData[5], _grid.SelectedItems);
    }

