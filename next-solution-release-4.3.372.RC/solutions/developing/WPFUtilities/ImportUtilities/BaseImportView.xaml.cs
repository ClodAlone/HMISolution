using System.Windows;
using System.Windows.Controls;
using System.Resources;
using System.Globalization;
using System.Threading;

namespace WPFUtilities
{
    /// <summary>
    /// Interaction logic for BaseImportView.xaml
    /// </summary>
    public partial class BaseImportView : UserControl
    {
        public BaseImportView()
        {
            InitializeComponent();
        }

        private void OnAutoGeneratedColumns(object sender, RoutedEventArgs e)
        {
            foreach (var col in gridDataControl.Columns)
            {
                string colHeaderText = Properties.Resources.ResourceManager.GetString($"EU_{col.FieldName}", Thread.CurrentThread.CurrentCulture);
                if (!string.IsNullOrEmpty(colHeaderText)) col.Header = colHeaderText;
            }
        }
    }
}
