using System;
using System.Net;

namespace DriverCodeBaseEx
{
    /// <summary>   Arguments for new data. </summary>
    public class NewDataReceivedArgs : EventArgs
    {
        ////////////////////////////////////////////////////////////////////////////////////////////////////
        /// <summary>   Gets or sets the receive bytes. </summary>
        ///
        /// <value> The receive bytes. </value>
        ////////////////////////////////////////////////////////////////////////////////////////////////////        
        public byte[] RxBytes { get; set; }

        ////////////////////////////////////////////////////////////////////////////////////////////////////
        /// <summary>   Data sender . </summary>
        ///
        /// <value> The receive bytes. </value>
        ////////////////////////////////////////////////////////////////////////////////////////////////////
        public object Sender { get; set; }

        ////////////////////////////////////////////////////////////////////////////////////////////////////
        /// <summary>   Gets or sets the Timestamp. </summary>
        ///
        /// <value> The Timestamp. </value>
        ////////////////////////////////////////////////////////////////////////////////////////////////////
        DateTime _Timestamp = default(DateTime);
        public DateTime Timestamp
        {
            get { return _Timestamp; }
            set { _Timestamp = value; }
        }

        ////////////////////////////////////////////////////////////////////////////////////////////////////
        /// <summary> Gets or sets execution of SetNewDataEvent method afer event execution. </summary>
        ///
        /// <value> The abilitation of SetNewDataEvent method execution. </value>
        ////////////////////////////////////////////////////////////////////////////////////////////////////
        bool _SetNewDataEvent = true;
        public bool SetNewDataEvent
        {
            get { return _SetNewDataEvent; }
            set { _SetNewDataEvent = value; }
        }
    }
}
