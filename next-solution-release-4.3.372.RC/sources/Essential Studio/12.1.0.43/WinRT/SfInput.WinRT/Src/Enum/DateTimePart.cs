namespace Syncfusion.UI.Xaml.Controls.Input
{
    /// <summary>
    /// specifies the DateTimePart with SfDateTimeCombo.
    /// </summary>
    public enum DateTimePart
    {
        /// <summary>
        /// Indicates Year DatePart in Selected DateTime.
        /// </summary>
        Year,

        /// <summary>
        /// Indicates Month DatePart in Selected DateTime.
        /// </summary>
        Month,

        /// <summary>
        /// Indicates Day DatePart in Selected DateTime.
        /// </summary>
        Day,

        /// <summary>
        /// Indicates 12 Hour TimePart in Selected DateTime.
        /// </summary>
        TwelveHour,

        /// <summary>
        /// Indicates 24 Hour TimePart in Selected DateTime.
        /// </summary>
        TwentyFourHour,

        /// <summary>
        /// Indicates Minute TimePart in Selected DateTime.
        /// </summary>
        Minute,

        /// <summary>
        /// Indicates Second TimePart in Selected DateTime.
        /// </summary>
        Second,

        /// <summary>
        /// Indicates AMPMDesignator TimePart in Selected DateTime.
        /// </summary>
        AMPMDesignator
    }
}
