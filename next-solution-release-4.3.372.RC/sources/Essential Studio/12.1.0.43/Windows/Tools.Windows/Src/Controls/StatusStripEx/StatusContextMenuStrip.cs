using System;
using System.Collections;
using System.Collections.Generic;
using System.ComponentModel;
using System.Drawing;
using System.Text;
using System.Windows.Forms;

using Syncfusion.Windows.Forms.Tools.Win32API;

namespace Syncfusion.Windows.Forms.Tools
{
    /// <summary>
    /// Context menu for StatusStripEx.
    /// </summary>
    [ToolboxItem(false)]
    public class StatusContextMenuStrip
        : ContextMenuStripEx
    {
        #region Constants
       private const int INTERNAL_PADDING = 20;
        #endregion

        #region Initialization
        /// <summary>
        /// Initializes a new instance of the StatusContextMenuStrip class.
        /// </summary>
        public StatusContextMenuStrip()
        {
        }
      
        /// <summary>
        /// Initializes a new instance of the StatusContextMenuStrip class.
        /// </summary>
        /// <param name="statusStrip">Status strip</param>
        public StatusContextMenuStrip(StatusStripEx statusStrip)
            : base(SR.GetString(System.Globalization.CultureInfo.CurrentCulture, "StatusStripMenuCaption", statusStrip))
        {
            this.StatusStrip = statusStrip;
        }
        #endregion

        #region Overrides
        protected override void Dispose(bool disposing)
        {
            if (disposing)
            {
                SR.ReleaseResources();
                this.StatusStrip = null;
            }
            base.Dispose(disposing);
        }

        /// <summary>
        /// Fills in Items collection.
        /// </summary>
        /// <param name="e"> EventArgs that contains the event data.</param>
        protected override void OnOpening(CancelEventArgs e)
        {
            StatusStripEx statusStrip = this.StatusStrip;

            if (statusStrip != null)
            {
                // Change Renderer if needed.
                if (this.Renderer != statusStrip.Renderer)
                {
                    this.Renderer = statusStrip.Renderer;
                }

                if (this.AutoGenerated)
                {
                    this.Items.Clear();

                    int iCounter = 0;
                    bool bSeparator = false;

                    foreach (ToolStripItem item in statusStrip.NotificationsItems)
                    {
                        IStatusItem statusItem = item as IStatusItem;

                        if (statusItem != null)
                        {
                            if (bSeparator)
                            {
                                this.Items.Add(new ToolStripSeparator());
                                bSeparator = false;
                            }

                            iCounter++;

                            // Set needed values to item before adding it to Items collection.
                            StatusMenuItem menuItem = new StatusMenuItem(item);

                            this.Items.Add(menuItem);

                            // Add separator if button indicates end of group.
                            if (statusItem.EndOfGroup && iCounter != 0)
                            {
                                bSeparator = true;
                                iCounter = 0;
                            }
                        }
                    }

                    if (statusStrip.StatusControlsItems.Count > 0 && statusStrip.NotificationsItems.Count > 0)
                    {
                        this.Items.Add(new ToolStripSeparator());
                    }

                    foreach (ToolStripItem item in statusStrip.StatusControlsItems)
                    {
                        ToolStripMenuItem menuItem = new StatusMenuItem(item);

                        this.Items.Add(menuItem);
                    }

                    e.Cancel = this.Items.Count == 0;
                }
            }

            base.OnOpening(e);
        }

        /// <summary>
        /// Cancels closing if needed.
        /// </summary>
        /// <param name="e"> EventArgs that contains the event data.</param>
        protected override void OnClosing(ToolStripDropDownClosingEventArgs e)
        {
            base.OnClosing(e);

            if (e.CloseReason == ToolStripDropDownCloseReason.ItemClicked)
            {
                e.Cancel = true;
            }
        }
      
        /// <summary>
        /// Performs item click on Space key.
        /// </summary>
        /// <param name="e"> EventArgs that contains the event data.</param>
        protected override void OnKeyDown(KeyEventArgs e)
        {
            switch (e.KeyCode)
            {
                case Keys.Space:
                    ToolStripMenuItem item = GetSelectedItem();
                    if (item != null)
                    {
                        item.PerformClick();
                    }
                    break;
                default:
                    base.OnKeyDown(e);
                    break;
            }
        }

        protected override void OnRendererChanged(EventArgs e)
        {
            base.OnRendererChanged(e);
        }
        #endregion

        #region Properties
        /// <summary>
        /// Gets or sets a value indicating whether user menu or custom menu need to be used.
        /// </summary>
        internal bool AutoGenerated
        {
            get
            {
                return m_bAutoGenerated;
            }

            set
            {
                if (m_bAutoGenerated != value)
                {
                    m_bAutoGenerated = value;
                }
            }
        }
        
        /// <summary>
        /// Gets or sets parent StatusStripEx.
        /// </summary>
        internal StatusStripEx StatusStrip
        {
            get
            {
                return m_header;
            }
            set
            {
                m_header = value;
            }
        }

        protected override Size MaxItemSize
        {
            get
            {
                Size szText = Size.Empty;
                Size szStatus = Size.Empty;

                foreach (ToolStripItem item in this.Items)
                {
                    StatusMenuItem statusItem = item as StatusMenuItem;
                    if (statusItem != null)
                    {
                        MaximizeSize(ref szText, GetTextSize(statusItem.Text));
                        MaximizeSize(ref szStatus, GetTextSize(statusItem.Status));
                    }
                }

                int width = szText.Width + this.Padding.Horizontal;

                if (szStatus.Width > 0)
                {
                    width += INTERNAL_PADDING + szStatus.Width;
                }

                int height = this.ImageScalingSize.Height;

                if (height < szText.Height)
                {
                    height = szText.Height;
                }

                if (height < szStatus.Height)
                {
                    height = szStatus.Height;
                }

                height += this.Padding.Vertical;

                return new Size(width, height);
            }
        }
        private void MaximizeSize(ref Size szTarget, Size szMin)
        {
            if (szTarget.Width < szMin.Width)
            {
                szTarget.Width = szMin.Width;
            }
            if (szTarget.Height < szMin.Height)
            {
                szTarget.Height = szMin.Height;
            }
        }
        #endregion

        #region Implementation

        private Size GetTextSize(string text)
        {
            if (!string.IsNullOrEmpty(text))
            {
                return TextRenderer.MeasureText(text, this.Font);
            }
            return Size.Empty;
        }

        private ToolStripMenuItem GetSelectedItem()
        {
            for (int i = 0, count = this.DisplayedItems.Count; i < count; i++)
            {
                ToolStripItem item = this.DisplayedItems[i];

                if (item.Selected)
                {
                    return item as ToolStripMenuItem;
                }
            }

            return null;
        }
        #endregion

        #region Fields
        /// <summary> Parent StatusStripEx. </summary>
        private StatusStripEx m_header;

        /// <summary> Indicates if user menu or custom menu need to be used. </summary>
        private bool m_bAutoGenerated = false;
        #endregion

        #region Nested classes

        internal class StatusMenuItem : ToolStripMenuItem
        {
            #region Constructors
    
            public StatusMenuItem(ToolStripItem item)
                : base()
            {
                this.ShowShortcutKeys = false;

                m_item = item;

                string text = item.Text;

                if (String.IsNullOrEmpty(text))
                {
                    text = item.Name;
                }

                this.Text = text;

                if (item is IStatusItem)
                {
                    IStatusItem statusItem = item as IStatusItem;

                    this.Checked = statusItem.Active;
                }
                else
                {
                    this.Checked = item.Available;
                }
            }
            #endregion

            #region Properties

            public string Status
            {
                get
                {
                    IStatusItem2 statusItem = m_item as IStatusItem2;
                    if (statusItem != null)
                    {
                        return statusItem.StatusString;
                    }
                    return null;
                }
            }
            #endregion

            #region Overrides

            protected override void SetBounds(Rectangle rect)
            {
                ToolStrip ts = this.Owner;

                if (ts != null)
                {
                    Rectangle rc = Rectangle.Inflate(ts.ClientRectangle, -1, 0);

                    rect.X = rc.X;

                    if (rect.Width < rc.Width)
                    {
                        rect.Width = rc.Width;
                    }
                }

                base.SetBounds(rect);
            }

            protected override void OnClick(EventArgs e)
            {
                base.OnClick(e);

                if (m_item is IStatusItem)
                {
                    IStatusItem statusItem = m_item as IStatusItem;

                    bool bActive = !statusItem.Active;

                    this.Checked = bActive;
                    statusItem.Active = bActive;
                }
                else
                {
                    bool bActive = !m_item.Available;

                    this.Checked = bActive;
                    m_item.Available = bActive;
                }
            }
            #endregion

            #region Fields

          private ToolStripItem m_item;
            #endregion
        }

        #endregion
    }
}

