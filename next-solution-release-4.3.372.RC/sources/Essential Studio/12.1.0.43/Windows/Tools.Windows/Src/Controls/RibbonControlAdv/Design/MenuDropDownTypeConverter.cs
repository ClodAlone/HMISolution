using System;
using System.ComponentModel;
using System.Windows.Forms;

namespace Syncfusion.Windows.Forms.Tools.Design
{
	#region  MenuButtonTypeConverter
	class MenuDropDownTypeConverter : ReferenceConverter
	{
		#region Constructors
		public MenuDropDownTypeConverter(Type type) : base(type)
		{ }
		#endregion

		#region Overrides
		/// <summary>
		/// 
		/// </summary>
		/// <param name="context"></param>
		/// <param name="culture"></param>
		/// <param name="value"></param>
		/// <param name="destinationType"></param>
		/// <returns></returns>
		public override object ConvertTo(ITypeDescriptorContext context, System.Globalization.CultureInfo culture, object value, Type destinationType)
		{
			if (destinationType == typeof(string))
			{
				ToolStripDropDown dropDown = value as ToolStripDropDown;

				if (dropDown != null && dropDown.IsAutoGenerated)
				{
					return null;
				}
			}
			return base.ConvertTo(context, culture, value, destinationType);
		}
		/// <summary>
		/// 
		/// </summary>
		/// <param name="context"></param>
		/// <param name="value"></param>
		/// <returns></returns>
		protected override bool IsValueAllowed(ITypeDescriptorContext context, object value)
		{
			ToolStripDropDown dropDown = value as ToolStripDropDown;

			if (dropDown != null && dropDown.IsAutoGenerated)
			{
				return false;
			}

			return base.IsValueAllowed(context, value);
		}
		#endregion
	}
	#endregion
}
#endif
