using System;
using System.Windows.Forms;
using System.Windows.Forms.Design;
using System.Drawing;
using System.ComponentModel;

namespace Syncfusion.Windows.Forms.Tools
{
	/// <summary>
	/// 
	/// </summary>
	[
	ToolStripItemDesignerAvailability( ToolStripItemDesignerAvailability.None )
	]
	class ToolStripMenuButton : ToolStripDropDownButton
	{
		#region Nested classes
		[ToolboxItem(false)]
		class Office2007MenuStrip : ToolStripDropDown
		{
			#region Constructors
			public Office2007MenuStrip()
			{
				m_panel = new ToolStripPanelItem();
				m_panel.ToolStrip.ShowCaption = false;
				m_panel.ToolStrip.BorderStyle = ToolStripBorderStyle.None;

				this.Items.Add( m_panel );
			}
			#endregion

			#region Fields
			ToolStripPanelItem m_panel;
			#endregion
		}
		#endregion

		#region Constructors
		public ToolStripMenuButton( RibbonControlAdvHeader parent )
		{
			this.Parent = parent;
		}
		#endregion

		#region Overrides
		/// <summary>
		/// 
		/// </summary>
		/// <returns></returns>
		protected override ToolStripDropDown CreateDefaultDropDown()
		{
			return new MenuDropDown( this );
		}
		/// <summary>
		/// 
		/// </summary>
		/// <param name="e"></param>
		protected override void OnDropDownShow( EventArgs e )
		{
			base.OnDropDownShow( e );

			ToolStripDropDown dropDown = this.DropDown;
			if( dropDown != null )
			{
				ToolStrip ts = this.GetCurrentParent();

				if (ts is RibbonControlAdvHeader)
				{
					RibbonControlAdvHeader header = ts as RibbonControlAdvHeader;
					if (header.RibbonStyle == RibbonStyle.Office2010 || header.RibbonStyle == RibbonStyle.Office2013)
					{
						return;
					}
				}

				if( ts != null )
				{
					this.DropDown.Renderer = ts.Renderer;
				}
				if( dropDown.IsAutoGenerated && this.DropDownItems.Count == 0 )
				{
					dropDown.OwnerItem = this;
					dropDown.Location = this.DropDownLocation;
					dropDown.Show();

					Invalidate();
				}
			}
		}

		protected override bool ProcessCmdKey(ref Message m, Keys keyData)
		{
			// SupperAccelerator does not receives the key press via IMessageFilter when,
			// menu putton is in pressed state.
			if (this.Parent != null
				&& (this.Parent as RibbonControlAdvHeader).SuperAccelerator != null)
			{
				(this.Parent as RibbonControlAdvHeader).SuperAccelerator.OnChar(ref m);
			}

			return base.ProcessCmdKey(ref m, keyData);
		}

		#endregion

		#region Properties
		/// <summary>
		/// 
		/// </summary>
		public override bool HasDropDownItems
		{
			get
			{
				return true;
			}
		}
		/// <summary>
		/// 
		/// </summary>
		protected override Point DropDownLocation
		{
			get
			{
				Point pt = base.DropDownLocation;

				MenuDropDown dropDown = this.DropDown as MenuDropDown;

				if( dropDown != null )
				{
					int offset = dropDown.Borders.Top - 4;

					if( offset > 0 )
					{
						pt.Y -= offset;
					}

					RibbonControlAdvHeader header = this.Parent as RibbonControlAdvHeader;

					if( header != null )
					{
						if( header.RightToLeft == RightToLeft.Yes )
						{
							pt.X = header.PointToScreen( new Point( this.Bounds.X + this.Width - dropDown.Width ) ).X + 1;
						}
					}
				}

				return pt;
			}
		}
		#endregion
	}
}
#endif